#define AUI_MIN_SIZE_THRESHOLD		(1<<0)
#define AUI_SPECIAL_CATEGORY		(1<<1)
#define AUI_HIDDEN_BY_OVERLAP		(1<<2) // also known as 'all probabilities'.
struct ANNOTATION_UI
{
	// info related to displaying and selecting the annotation in the UI, i.e, data that is *not* read from, or saved to, the CSV file. Its a wasteful having
	// a ANNOTATION_UI in each CLASSIFIEDLINE, because we only need this data for the CLASSIFIEDLINE's currently displayed in the UI. However, having it in every CLASSIFIEDLINE
	// makes the code very simple so its worth the wasted memory.
	// (note to me - cant use a ANNOTATION_UI pointer because the CLASSIFIEDLINE elements are copied and shuffled around during editing).
	RECT Screen;		// screen coordinates.
	int  Selected;		// selected by SELECTION_EDITING or SELECTION_HIGHLIGHT.
	int  auiFlags;
	int  AllProbsIndex;	// index to accompany AUI_HIDDEN_BY_OVERLAP flag.
};

struct CLASSIFIEDLINE
{
	ANNOTATION_UI Anno_UI;
#ifdef ALLOW_ANNOTATION_FILTER
	int  AnnotationFilter;	// only used during yolo export.
#endif
	int  ClassId;			// must be signed as we can have negative class_id to signify a 'negative' image.
	int  Model_Code;
	int  DebugCode;
	BBOX box;
};

#define NUM_SPARE_ANNOTATIONS	12
struct CLASSIFIEDLINE_CONTAINER
{
	CLASSIFIEDLINE *pLines;	// list - lines which have been 'classified', i.e. edited in the GUI.
	int Max, Num, NumSpare;

	void Initialise()
	{	Num = Max = 0;
		pLines = nullptr;	// memory is realloc'ed and kept for program lifetime.
	}
	void Reset()
	{	Num = 0;
		NumSpare = NUM_SPARE_ANNOTATIONS;
	}
	void FreeMem()
	{	free(pLines);
	}
};

