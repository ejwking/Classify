struct SOURCELINEREPEATS
{
	// 'source line repeats' - data thats common for all csv lines relating to the same picture (filename group).
	// data here is read in from csv lines and **NEVER** modified afterwards (modified annotation data is kept in CLASSIFIEDLINE).
	// 
	// one buffer pointer for the entire filename group? I did this but it caused problems when merging, so not doing it anymore.
	int   Time_Stamp;
	char *pfile_name;
	int   Width, Height;
	int   Pic_classified;	// classified status from the csv line, not used in the UI. In the UI FILENAMEGROUP::Classified is the flag used.
	int   PictureCode;		// enum PICTURECODE
	int   ColourCode;		// enum COLOURCODE
};

struct SOURCELINE			// a single 'source csv line' (i.e. read in from the original csv file) 
{
	BYTE rsvd_best, rsvd_id;// used in FixAndCropPictures.
//	short rsvd_best;

	int   FilenameCount;
	SOURCELINEREPEATS Repeats;
	int   model_code;		// which model generated this annotation.
	int   Confidence;		// (only used for merging annotations from different models).
	int   ClassId;			// negative id signifies a 'negative' picture.
	int   DebugCode;		// used to display merging decisions in the UI.
	BBOX  Box;
};

struct SOURCELINE_CONTAINER
{
	SOURCELINE *pCsvLns;	// list - the source lines for *all* loaded csv files.
	int   Num, Max;
	int   NumFilenames;
	int   EstimateNum, LargestFnGrp;
	int   Format;
	char *pPreviousFilename;
	void Initialise()
	{	Num = Max = 0;
		EstimateNum = 0;
		pCsvLns = nullptr;	// memory is realloc'ed and kept for program lifetime.
	}
	void Reset()
	{	Num = NumFilenames = LargestFnGrp = 0;
		pPreviousFilename = nullptr;
		Format = CSVFORMAT::CSV_NOT_SET;
	}
	void FreeMem()
	{	free(pCsvLns);
	}
};

