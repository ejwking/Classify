struct FILENAMEGROUP
{
	SOURCELINEREPEATS *pPicInfo;

	// source lines - The original csv lines for this filename group.
	SOURCELINE *pSourceLines;
	int NumSourceLines;

	// ..and the classified lines ..ie the editted/classified annotations for this picture.
	CLASSIFIEDLINE *pClsfdLines;
	int NumClsfdLines, MaxClsfdLines;
	int Classified;	// CLASSIFIED_STATUS
	int Timestamp;
};

